// 정산 시트 시험용 합성 데이터(실제 시트의 이름·금액이 아니다). 가짜 서버와 시험이 같은 값을 쓰고, 기대 합계도 여기서 함께 정한다.
const HEADER = ["구분", "광고주", "프로젝트명", "인플루언서명", "인플루언서 비용", "공제 후 금액", "광고주 계약 매출", "업로드 여부", "업로드 URL", "결제 여부", "결제일", ""];
const R = (...c) => { const r = Array(12).fill(""); c.forEach((v, i) => (r[i] = v)); return r; };
const W = (n) => `₩${n.toLocaleString("en-US")}`;

function rows() {
  const out = [HEADER];
  // 법인A 50명: 비용 100,000 · 공제 후 96,700 · 매출 150,000. 앞 30명은 결제 완료(결제일 있음), 나머지 20명은 결제 대기
  for (let i = 1; i <= 50; i++) {
    const paid = i <= 30;
    out.push(R("법인A", "광고주1", "프로젝트X", `가수${i}`, W(100000), W(96700), W(150000), "O", `https://example.com/v/${i}`, paid ? "결제 완료" : "결제 대기", paid ? `2026-05-${String(i).padStart(2, "0")}` : ""));
  }
  // 법인B 5명: 비용만 있음(공제 후 빈칸) · 매출 300,000. 앞 2명은 결제 완료, 뒤 3명은 결제 여부 빈칸
  for (let i = 1; i <= 5; i++) {
    out.push(R("법인B", "광고주2", "프로젝트Y", `나수${i}`, W(200000), "", W(300000), "O", "", i <= 2 ? "결제 완료" : "", i <= 2 ? "2026-06-01" : ""));
  }
  out.push(R("법인B", "광고주2", "프로젝트Y", "다수1", W(50000), W(48350), "#REF!", "O", "", "결제 완료", "2026.06.10 09:00")); // 매출이 오류값
  out.push(Array(12).fill("")); // 빈 행
  out.push(R("", "", "", "", W(9999999), W(9999999), W(9999999))); // 합계 행(목록에서 제외돼야 함)
  out.push(R("법인A", "광고주3", "프로젝트X", "라수1", W(80000), W(77360), W(120000), "O", "", "환불", "2026-05-02")); // 환불
  out.push(R("법인A", "광고주3", "프로젝트X", "마수1", W(70000), W(67690), W(90000), "final_cut.mp4", "", "결제 대기", "")); // 업로드 칸에 파일명
  return out;
}

